#!/usr/bin/env bash
# Build a Python 3.11 venv + sidecar for Tauri production bundles.
# Output: src-tauri/resources/python/venv/ (gitignored; included via bundle.resources)
set -euo pipefail

export PIP_DEFAULT_TIMEOUT="${PIP_DEFAULT_TIMEOUT:-180}"
export PIP_RETRIES="${PIP_RETRIES:-15}"

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
# shellcheck source=scripts/resolve-bundled-python.sh
source "${ROOT}/scripts/resolve-bundled-python.sh"

TAG="$(resolve_python_platform_tag)"
OUT="${ORCAI_PYTHON_CACHE_DIR:-${HOME}/.cache/orcai-desktop/python-bundle-${TAG}}"
SIDECAR="${ROOT}/apps/sidecar"
VENV="${OUT}/venv"
LINK_TARGET="${ROOT}/src-tauri/resources/python"

echo "orcAI Desktop: bundle Python → ${VENV}"
echo "  (cache root: ${OUT})"

if ! command -v python3.11 >/dev/null 2>&1; then
  echo "Install Python 3.11 (e.g. brew install python@3.11)" >&2
  exit 1
fi

if [[ -d "${OUT}" ]]; then
  chmod -R u+w "${OUT}" 2>/dev/null || true
  rm -rf "${OUT}"
fi
mkdir -p "${OUT}"

# --copies: embed interpreter copies (better for bundling into .app / installer)
python3.11 -m venv --copies "${VENV}"
# shellcheck disable=SC1091
source "${VENV}/bin/activate"

pip install --upgrade pip wheel

ORCAI_REF="${ORCAI_GIT_REF:-v3.0.4}"

install_sidecar() {
  pip install "${SIDECAR}[analytics]"
}

install_sidecar_tarball() {
  local ref="${ORCAI_REF}"
  local tgz="/tmp/orcAI-${ref}.tar.gz"
  local need_fetch=true
  if [[ -f "${tgz}" ]] && tar -tzf "${tgz}" >/dev/null 2>&1; then
    need_fetch=false
  else
    rm -f "${tgz}"
  fi
  if [[ "${ORCAI_REFRESH_TARBALL:-}" == "1" ]]; then
    need_fetch=true
  fi
  if [[ "${need_fetch}" == "true" ]]; then
    echo "Fetching orcAI tarball (ref=${ref})…"
    curl -fsSL -o "${tgz}" "https://github.com/ethz-tb/orcAI/archive/refs/tags/${ref}.tar.gz"
  fi
  pip install "uv_build>=0.11.2,<0.14.0" wheel setuptools
  pip install "${tgz}"
  pip install "${SIDECAR}[analytics]" --no-deps
  pip install "fastapi>=0.115.0" "uvicorn[standard]>=0.32.0" "pydantic>=2.0" "pillow>=10.0" "soundfile>=0.12.0" "duckdb>=1.0"
}

if [[ "${ORCAI_BUNDLE_MODE:-}" == "tarball" ]] || [[ "${ORCAI_REF}" =~ ^v[0-9] ]]; then
  install_sidecar_tarball
elif install_sidecar 2>/tmp/orcai-pip-sidecar.log; then
  :
else
  echo "pip git install failed ($(tail -1 /tmp/orcai-pip-sidecar.log 2>/dev/null)); recreating venv + tarball…" >&2
  deactivate 2>/dev/null || true
  chmod -R u+w "${OUT}" 2>/dev/null || true
  rm -rf "${OUT}"
  mkdir -p "${OUT}"
  python3.11 -m venv --copies "${VENV}"
  # shellcheck disable=SC1091
  source "${VENV}/bin/activate"
  pip install --upgrade pip wheel
  install_sidecar_tarball
fi

install_macos_metal() {
  if [[ "$(uname -s)" == "Darwin" && "$(uname -m)" == "arm64" ]]; then
    echo "macOS arm64: TensorFlow 2.18.1 + tensorflow-metal (Apple GPU)…"
    pip install --upgrade --force-reinstall \
      "tensorflow==2.18.1" "tensorflow-metal==1.2.0"
    python -c "
from pathlib import Path
import site, tensorflow as tf
dylib = next(
    (p / 'tensorflow-plugins' / 'libmetal_plugin.dylib' for p in map(Path, site.getsitepackages()) if (p / 'tensorflow-plugins' / 'libmetal_plugin.dylib').is_file()),
    None,
)
print('TF', tf.__version__, 'metal_dylib', dylib, 'GPUs', tf.config.list_physical_devices('GPU'))
"
  fi
}

install_macos_metal

# Marker for support / debugging + verify bundled built-in models
python -c "
import orcai_desktop_sidecar
import orcai
from orcai_desktop_sidecar.adapters.models import verify_builtin_models_bundle
models = verify_builtin_models_bundle()
print('orcAI sidecar bundle OK')
print('Built-in models:', ', '.join(m['id'] for m in models))
"

echo "=== Make venv portable (no Homebrew symlinks) ==="
bash "${ROOT}/scripts/make-python-venv-portable.sh" "${VENV}"
# Python.framework is embedded into the .app after `tauri build` (see build-macos-release.sh).

# Cache-only placeholder cfg (no framework beside this venv yet).
# Portable relative pyvenv.cfg + bash stubs are applied LAST by
# scripts/embed-python-in-built-app.sh → embed-python-framework.sh --wrappers-only.
PYVER="$(python -c 'import sys; print(f"{sys.version_info.major}.{sys.version_info.minor}")')"
cat > "${VENV}/pyvenv.cfg" <<EOF
home = .
include-system-site-packages = false
version = ${PYVER}
executable = bin/python3
command = bin/python3 -m venv --copies .
EOF

printf '%s\n' "$(uname -s)/$(uname -m)" > "${OUT}/BUNDLE_PLATFORM"

cat > "${OUT}/README.txt" <<EOF
Bundled Python for orcAI Desktop (orcAI ${ORCAI_REF}, generated by scripts/bundle-python.sh).
Build on the same OS/arch as the release target (macOS arm64, Windows x64, etc.).
On macOS arm64, tensorflow==2.18.1 + tensorflow-metal==1.2.0 are installed for GPU (Metal).
Tauri resolves: \$RESOURCE/python/venv/bin/python3
Platform stamp: $(cat "${OUT}/BUNDLE_PLATFORM")
EOF

export_orcai_bundled_python_env "/tmp/orcai-desktop-bundled-python.env" "${OUT}"
bash "${ROOT}/scripts/link-bundled-python.sh" "${OUT}" || {
  echo "Note: could not link ${LINK_TARGET} → ${OUT}" >&2
  echo "  Dev still works via ORCAI_BUNDLED_PYTHON_DIR=${OUT}" >&2
}

echo "Done. Venv size: $(du -sh "${VENV}" | cut -f1)"
echo "Cache root: ${OUT}"
